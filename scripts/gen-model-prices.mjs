#!/usr/bin/env node
/* Builds app/model-prices-data.js from the price seed in CC Switch (MIT, see docs/THIRD_PARTY.md).
   Usage: CC_SWITCH_SRC=<checkout of the CC Switch repo> node scripts/gen-model-prices.mjs
   Prices are USD per million tokens (input, output, cache read). Static data, never fetched at run time. */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.env.CC_SWITCH_SRC;
if (!src) { console.error('set CC_SWITCH_SRC to the CC Switch checkout'); process.exit(1); }
const here = path.dirname(fileURLToPath(import.meta.url));
const schema = readFileSync(path.join(src, 'src-tauri/src/database/schema.rs'), 'utf8');
const start = schema.indexOf('fn seed_model_pricing');
const end = schema.indexOf('\n    }\n', start);
const body = schema.slice(start, end);
const pattern = /\(\s*"([^"]+)",\s*"([^"]+)",\s*"([\d.]+)",\s*"([\d.]+)",\s*"([\d.]+)",\s*"([\d.]+)",?\s*\)/g;
const models = [], seen = new Set();
for (const match of body.matchAll(pattern)) {
  const [, id, name, input, output, cacheRead] = match;
  if (seen.has(id)) continue;
  seen.add(id);
  models.push({ id: id.toLowerCase(), name, input: Number(input), output: Number(output), cacheRead: Number(cacheRead) });
}
const header = `/* Model price table (USD per million tokens), generated by scripts/gen-model-prices.mjs from the MIT-licensed CC Switch price seed.
   Copyright (c) 2025 Jason Young (CC Switch). The licence text and registration are in docs/THIRD_PARTY.md. Static data: never fetched at run time. */
(function (root, factory) {
  const data = factory();
  if (typeof module === 'object' && module.exports) module.exports = data;
  else root.ModelPriceData = data;
}(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  'use strict';
  return `;
writeFileSync(path.join(here, '..', 'app', 'model-prices-data.js'), header + JSON.stringify({ version: 1, currency: 'USD', models }) + ';\n}));\n');
console.log(`wrote ${models.length} prices`);
