import Foundation
@main struct NativeSettingsRegistryTests {
 static func main() {
  var checks=0
  func check(_ value:Bool,_ label:String){precondition(value,label);checks+=1;print("PASS",label)}
  func parse(_ b:[String:Any])->NativeSettingsRegistry.Rejection?{if case .failure(let r)=NativeSettingsRegistry.parse(b){return r};return nil}
  func set(_ id:Any,_ v:Any)->[String:Any]{["command":"native-settings","action":"set","id":id,"value":v]}
  check(parse(["command":"native-settings","action":"state"]) == nil,"state accepted")
  check(parse(["command":"native-settings","action":"state","id":"login.enabled"]) == .invalidRequest,"state with extra key rejected")
  check(parse(["command":"native-settings"]) == .invalidRequest,"missing action rejected")
  check(parse(["command":"native-settings","action":"wipe"]) == .invalidRequest,"unknown action rejected")
  check(parse(set("login.enabled",true)) == nil,"known bool id accepted")
  check(parse(set("no.such.id",true)) == .invalidRequest,"unknown id rejected")
  check(parse(set("com.apple.AIBroLoginInBackground",true)) == .invalidRequest,"raw defaults key rejected")
  check(parse(set(String(repeating:"a",count:200),true)) == .invalidRequest,"oversized id rejected")
  check(parse(set(5,true)) == .invalidRequest,"non-string id rejected")
  check(parse(set("login.enabled",1)) == .invalidRequest,"number for bool rejected")
  check(parse(set("login.enabled",NSNumber(value:1))) == .invalidRequest,"non-boolean NSNumber for bool rejected")
  check(parse(set("login.enabled","true")) == .invalidRequest,"string for bool rejected")
  check(parse(set("dictate.trigger",true)) == .invalidRequest,"bool for choice rejected")
  check(parse(set("dictate.trigger",1)) == .invalidRequest,"number for choice rejected")
  check(parse(set("dictate.trigger","leftShift")) == .invalidRequest,"choice outside list rejected")
  check(parse(set("dictate.trigger","combo")) == nil,"valid choice accepted")
  check(parse(set("speech.silence",1.5)) == nil,"number in range accepted")
  check(parse(set("speech.silence",0)) == nil,"zero (off) accepted")
  check(parse(set("speech.silence",11)) == .invalidRequest,"number above range rejected")
  check(parse(set("speech.silence",-1)) == .invalidRequest,"negative number rejected")
  check(parse(set("speech.silence",true)) == .invalidRequest,"bool for number rejected")
  check(parse(set("speech.silence","1.5")) == .invalidRequest,"string for number rejected")
  check(parse(set("speech.silence",Double.nan)) == .invalidRequest,"NaN rejected")
  check(parse(set("dictate.combo","4096:2")) == nil,"shortcut string accepted")
  check(parse(set("dictate.combo","4096")) == .invalidRequest,"shortcut without key rejected")
  check(parse(set("dictate.combo","a:b")) == .invalidRequest,"non-numeric shortcut rejected")
  check(parse(set("dictate.combo",4096)) == .invalidRequest,"number for shortcut rejected")
  check(parse(set("dictate.access",true)) == .invalidRequest,"read-only id cannot be set")
  check(parse(set("quickPanel.section.clipboard",false)) == nil,"section family accepted")
  check(parse(set("quickPanel.home.tasks",true)) == nil,"home family accepted")
  check(parse(set("quickPanel.size.tasks","large")) == nil,"size family accepted")
  check(parse(set("quickPanel.size.tasks","huge")) == .invalidRequest,"bad size rejected")
  check(parse(set("quickPanel.move.tasks","up")) == nil,"move family accepted")
  check(parse(set("quickPanel.move.","up")) == .invalidRequest,"empty family suffix rejected")
  check(parse(set("quickPanel.home.a/b",true)) == .invalidRequest,"family suffix charset enforced")
  check(parse(set("quickPanel.reset","run")) == nil,"action accepted")
  check(parse(set("quickPanel.reset","now")) == .invalidRequest,"action with other value rejected")
  check(parse(set("clipboard.retention.preview","30:50")) == nil,"retention preview accepted")
  check(parse(set("clipboard.retention.preview","0:100")) == nil,"retention no age limit accepted")
  check(parse(set("clipboard.retention.preview","5:50")) == .invalidRequest,"retention days outside list rejected")
  check(parse(set("clipboard.retention.preview","30:7")) == .invalidRequest,"retention limit outside list rejected")
  check(NativeSettingsRegistry.shortcut("4096:2")?.keyCode == 2,"shortcut parsed")
  check(NativeSettingsRegistry.retention("0:25")?.days == nil,"retention 0 means no age limit")
  var extra=set("login.enabled",true);extra["x"]=1
  check(parse(extra) == .invalidRequest,"extra key rejected")
  var missing=set("login.enabled",true);missing.removeValue(forKey:"value")
  check(parse(missing) == .invalidRequest,"missing value rejected")
  let w=NativeSettingsRegistry.Request.set(id:"login.enabled",value:.bool(true))
  check(NativeSettingsRegistry.visibility(for:.state,ready:false,selection:nil) == nil,"state readable anywhere")
  check(NativeSettingsRegistry.visibility(for:w,ready:true,selection:"settings") == nil,"set allowed on ready settings page")
  check(NativeSettingsRegistry.visibility(for:w,ready:true,selection:"overview") == .settingsNotVisible,"set rejected on other page")
  check(NativeSettingsRegistry.visibility(for:w,ready:true,selection:nil) == .settingsNotVisible,"set rejected without selection")
  check(NativeSettingsRegistry.visibility(for:w,ready:false,selection:"settings") == .settingsNotVisible,"set rejected when workspace not ready")
  check(NativeSettingsRegistry.reply(.invalidRequest)["reason"] as? String == "invalid_request","reply carries reason")
  func setReq(_ id:String,_ v:Any)->NativeSettingsRegistry.Rejection?{parse(["command":"native-settings","action":"set","id":id,"value":v])}
  check(setReq("perm.accessibility",true) == .invalidRequest,"permission status is read-only")
  check(setReq("perm.open.accessibility","run") == nil,"permission open action accepted")
  check(setReq("agenda.taskReminder","30") == .invalidRequest,"reminder choice outside list rejected")
  check(setReq("agenda.taskReminder","15") == nil,"reminder choice accepted")
  check(setReq("agenda.briefingHour",24.0) == .invalidRequest,"briefing hour out of range rejected")
  check(setReq("agenda.briefingMinute",30.0) == nil,"briefing minute accepted")
  check(setReq("notify.external",true) == nil,"external notification toggle accepted")
  check(setReq("notify.history.clear","run") == nil,"history clear action accepted")
  check(parse(set("notify.hook.codex","run")) == nil,"hook command action accepted")
  check(parse(set("notify.hook.codex","x")) != nil,"hook action rejects a non-run value")
  check(parse(set("notify.hook.codex",true)) != nil,"hook action rejects a bool")
  print("native settings registry checks:",checks)
 }
}
